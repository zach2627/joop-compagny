export const dictionaries = { fr, en } as const;

export type Dictionary = (typeof dictionaries)[Locale];

export function translateCategory(
  locale: Locale,
  category: { slug?: string | null; name: string }
): string {
  const slug = category.slug;
  const categories = dictionaries[locale].categories as Record<string, string>;
  return slug && categories[slug] ? categories[slug] : category.name;
}
